'use client';

import { usePathname } from 'next/navigation';
import { Link } from '@/i18n/navigation';

const navItems = [
  { href: '/dashboard', label: 'Overview', icon: GridIcon },
  { href: '/dashboard/wallet', label: 'Wallet', icon: WalletIcon },
  { href: '/dashboard/profile', label: 'Profile', icon: UserIcon },
];

export function DashboardSidebar() {
  const pathname = usePathname();

  // Strip locale prefix for matching (e.g., "/en/dashboard" → "/dashboard")
  const strippedPath = pathname.replace(/^\/[a-z]{2}(?=\/)/, '');

  return (
    <nav className="w-48 shrink-0 border-r border-white/10 py-6 px-3 space-y-1 hidden md:block">
      {navItems.map(({ href, label, icon: Icon }) => {
        const isActive =
          href === '/dashboard'
            ? strippedPath === '/dashboard'
            : strippedPath.startsWith(href);
        return (
          <Link
            key={href}
            href={href}
            className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors ${
              isActive
                ? 'bg-white/10 text-white font-medium'
                : 'text-gray-400 hover:text-white hover:bg-white/5'
            }`}
          >
            <Icon className="w-4 h-4 shrink-0" />
            {label}
          </Link>
        );
      })}
    </nav>
  );
}

